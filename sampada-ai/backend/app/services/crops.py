"""Crop and soil knowledge base.

Loads the reference tables from ``app/data``. ``crops.json`` is generated by
``scripts/build_crop_table.py`` from cited sources (FAO EcoCrop for
environmental requirements, FAO-56 Tables 11 and 12 for durations and crop
coefficients) and carries a per-field ``provenance`` block. Read that block
before trusting a number - several fields are derived, and a few are explicitly
curated judgement.

Display names live in the locale files (``crop.<id>`` and ``enum.soil_type.<id>``)
rather than in these tables, so every farmer-facing string in the app is covered
by the same translation-completeness check and the same review process.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import lru_cache
from typing import Any

from ..core.config import DATA_DIR
from ..core.i18n import t

CROPS_PATH = DATA_DIR / "crops.json"
SOIL_PATH = DATA_DIR / "soil_types.json"

VALID_SEASONS = ("KHARIF", "RABI", "SUMMER", "PERENNIAL")

# Water-need classes mapped onto a comparable 0..1 scale. These are the
# capacity the crop needs to be met, on the same axis as
# suitability.farm_water_capacity.
WATER_CLASS_SCORE = {"LOW": 0.30, "MEDIUM": 0.60, "HIGH": 0.90}


@dataclass(slots=True)
class Crop:
    id: str
    scientific_name: str
    seasons: list[str]
    duration_days: list[int]
    water_need_class: str
    temp_optimal_c: list[float]
    temp_absolute_c: list[float]
    rainfall_optimal_mm: list[float]
    rainfall_absolute_mm: list[float]
    ph_optimal: list[float]
    ph_absolute: list[float]
    # None means the source records no texture preference for this crop. That is
    # deliberately distinct from an empty list, which would read as "no soil suits it".
    soil_types_optimal: list[str] | None
    soil_types_tolerated: list[str]
    kc: dict[str, Any]
    investment_level: str
    major_risks: list[str]
    # Advisory package-of-practices block (sowing window, seed rate, fertilizer
    # dose, verbatim quotes) transcribed from government/ICAR publications.
    # None for crops with no local transcription yet. Advisory only: the scoring
    # engine never reads it - seasons drive seasonal fit.
    pop: dict[str, Any] | None = None
    provenance: dict[str, Any] = field(default_factory=dict)

    def name(self, lang: str) -> str:
        return t(lang, f"crop.{self.id}")

    @property
    def water_score(self) -> float:
        return WATER_CLASS_SCORE.get(self.water_need_class, 0.60)

    @property
    def has_soil_preference(self) -> bool:
        return self.soil_types_optimal is not None

    @property
    def temp_bounds_optimal(self) -> tuple[float, float] | None:
        if len(self.temp_optimal_c) >= 2:
            return float(self.temp_optimal_c[0]), float(self.temp_optimal_c[1])
        return None

    @property
    def temp_bounds_absolute(self) -> tuple[float, float] | None:
        if len(self.temp_absolute_c) >= 2:
            return float(self.temp_absolute_c[0]), float(self.temp_absolute_c[1])
        return self.temp_bounds_optimal

    @property
    def investment_risk(self) -> float:
        return {"LOW": 0.2, "MEDIUM": 0.5, "HIGH": 0.8}.get(self.investment_level, 0.5)


@dataclass(slots=True)
class SoilType:
    id: str
    texture_class: str
    ecocrop_drainage: str
    water_retention: str
    drainage: str
    cracks_in_summer: bool
    sticky_when_wet: bool
    rain_behaviour_likelihood: dict[str, float] = field(default_factory=dict)

    def name(self, lang: str) -> str:
        return t(lang, f"enum.soil_type.{self.id}")


@lru_cache(maxsize=1)
def load_crops() -> dict[str, Crop]:
    with open(CROPS_PATH, encoding="utf-8") as handle:
        payload = json.load(handle)
    crops: dict[str, Crop] = {}
    for row in payload.get("crops", []):
        optimal = row.get("soil_types_optimal")
        crop = Crop(
            id=row["id"],
            scientific_name=str(row.get("scientific_name", "")),
            seasons=list(row.get("seasons", [])),
            duration_days=list(row.get("duration_days", [])),
            water_need_class=str(row.get("water_need_class", "MEDIUM")),
            temp_optimal_c=list(row.get("temp_optimal_c") or []),
            temp_absolute_c=list(row.get("temp_absolute_c") or []),
            rainfall_optimal_mm=list(row.get("rainfall_optimal_mm") or []),
            rainfall_absolute_mm=list(row.get("rainfall_absolute_mm") or []),
            ph_optimal=list(row.get("ph_optimal") or []),
            ph_absolute=list(row.get("ph_absolute") or []),
            soil_types_optimal=list(optimal) if optimal is not None else None,
            soil_types_tolerated=list(row.get("soil_types_tolerated") or []),
            kc=dict(row.get("kc", {})),
            investment_level=str(row.get("investment_level", "MEDIUM")),
            major_risks=list(row.get("major_risks", [])),
            pop=dict(row["pop"]) if row.get("pop") else None,
            provenance=dict(row.get("provenance", {})),
        )
        crops[crop.id] = crop
    return crops


@lru_cache(maxsize=1)
def load_soil_types() -> dict[str, SoilType]:
    with open(SOIL_PATH, encoding="utf-8") as handle:
        payload = json.load(handle)
    soils: dict[str, SoilType] = {}
    for row in payload.get("soil_types", []):
        soil = SoilType(
            id=row["id"],
            texture_class=str(row.get("texture_class", "")),
            ecocrop_drainage=str(row.get("ecocrop_drainage", "")),
            water_retention=str(row.get("water_retention", "MEDIUM")),
            drainage=str(row.get("drainage", "MEDIUM")),
            cracks_in_summer=bool(row.get("cracks_in_summer", False)),
            sticky_when_wet=bool(row.get("sticky_when_wet", False)),
            rain_behaviour_likelihood=dict(row.get("rain_behaviour_likelihood", {})),
        )
        soils[soil.id] = soil
    return soils


@lru_cache(maxsize=1)
def crop_provenance() -> dict[str, Any]:
    with open(CROPS_PATH, encoding="utf-8") as handle:
        return dict(json.load(handle).get("_meta", {}))


@lru_cache(maxsize=1)
def soil_provenance() -> dict[str, Any]:
    with open(SOIL_PATH, encoding="utf-8") as handle:
        return dict(json.load(handle).get("_meta", {}))


@lru_cache(maxsize=1)
def typical_crops_for_soil() -> dict[str, list[str]]:
    """Crops this soil is an *optimal* match for, inverted from the crop table.

    Derived rather than hand-listed so the two tables cannot disagree. A crop
    whose soil preference is unknown contributes to no soil.
    """
    result: dict[str, list[str]] = {soil_id: [] for soil_id in load_soil_types()}
    for crop in load_crops().values():
        for soil_id in crop.soil_types_optimal or []:
            if soil_id in result:
                result[soil_id].append(crop.id)
    return result


def crop_name(crop_id: str, lang: str) -> str:
    crop = load_crops().get(crop_id)
    return crop.name(lang) if crop else crop_id


def soil_name(soil_id: str, lang: str) -> str:
    soil = load_soil_types().get(soil_id)
    return soil.name(lang) if soil else soil_id


def infer_season(month: int) -> str:
    """Infer the agricultural season from a calendar month (Maharashtra).

    Kharif Jun-Oct, Rabi Nov-Feb, Summer Mar-May. This is a convention, and it is
    the same convention recorded per crop in crop_agronomy_curated.json. It is
    NOT a per-crop sowing window - this project deliberately has no sourced
    per-crop sowing dates.
    """
    if 6 <= month <= 10:
        return "KHARIF"
    if month in (11, 12, 1, 2):
        return "RABI"
    return "SUMMER"


def water_behaviour_distribution(behaviour: str) -> dict[str, float]:
    """Turn a farmer's rain-behaviour answer into a soil-type distribution.

    The likelihoods in the reference table are *relative* and are explicitly
    uncalibrated; they are normalized here so the result is a proper
    distribution.
    """
    behaviour = behaviour.upper()
    raw: dict[str, float] = {}
    for soil_id, soil in load_soil_types().items():
        value = soil.rain_behaviour_likelihood.get(behaviour)
        if value:
            raw[soil_id] = float(value)
    total = sum(raw.values())
    if total <= 0:
        return {}
    return {soil_id: value / total for soil_id, value in raw.items()}
